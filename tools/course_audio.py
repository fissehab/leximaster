"""Recordings for the English course (static/js/course-lessons.js): every
example, every ✗ and ✓ sentence and every listening question, said by Kokoro
as tools/tts.py says the entries, and checked by ear the same way (Whisper
base.en; another voice when it hears something else).

    .venv/bin/python tools/course_audio.py      # make what's new or changed, then write the map

Files: data/tts/course/<slug>.<hash>.m4a (published under media/ by
build_site.py); manifest data/cache/course_tts.json; the map the lesson
page plays from, static/js/course-audio.js ({spoken text: file}). Free.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import tts  # noqa: E402

MANIFEST = tts.CACHE / "course_tts.json"
OUT_DIR = tts.OUT_DIR / "course"
MAP = ROOT / "static" / "js" / "course-audio.js"
PASS = 0.85          # how close Whisper's transcript must be to the sentence (letters, 0–1)
SENTENCE_PAUSE = 0.35  # seconds between sentences ("Look! It's snowing.")


def sentences() -> list[dict]:
    """Every sentence the lessons say aloud, from the lesson file itself
    (static/js/course-text.js lessonSentences), in lesson order."""
    js = ("import { LESSONS } from './static/js/course-lessons.js';"
          "import { lessonSentences } from './static/js/course-text.js';"
          "console.log(JSON.stringify(LESSONS.flatMap(l => lessonSentences(l).map(s => ({...s, lesson: l.id})))));")
    out = subprocess.run(["node", "--input-type=module", "-e", js], cwd=ROOT, capture_output=True, text=True, check=True)
    seen, rows = set(), []
    for r in json.loads(out.stdout):
        if r["key"] not in seen:
            seen.add(r["key"])
            rows.append(r)
    return rows


def say(kokoro, text: str, voice: str):
    """Kokoro's reading of the text, a short silence between sentences and
    at commas (tts.synth)."""
    import numpy as np
    parts = [p for p in re.split(r"(?<=[.!?])\s+", text.strip()) if p]
    out, sr = [], 24000
    for i, p in enumerate(parts):
        audio, sr = tts.synth(kokoro, kokoro.tokenizer.phonemize(p), voice, tts.SPEED)
        if i:
            out.append(np.zeros(int(sr * SENTENCE_PAUSE), dtype=audio.dtype))
        out.append(audio)
    return np.concatenate(out), sr


def write_map(m: dict, keys: list[str]) -> None:
    data = {k: m[k]["file"] for k in keys if k in m}
    MAP.write_text("// Generated by tools/course_audio.py: the recording of each sentence the English\n"
                   "// course says aloud (static/js/course-lessons.js), by its spoken text. Files under media/.\n"
                   "export const AUDIO = " + json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True) + ";\n",
                   encoding="utf-8")


def main() -> int:
    from kokoro_onnx import Kokoro
    rows = sentences()
    m = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    todo = [r for r in rows if r["key"] not in m or not (tts.DATA / m[r["key"]]["file"]).exists()]
    print(f"{len(rows)} sentences, {len(todo)} to record", flush=True)
    if todo:
        kokoro = Kokoro(str(tts.MODEL), str(tts.VOICES))
        base = tts._whisper("base.en")
        t0, stuck = time.time(), []
        for n, r in enumerate(todo, 1):
            text = r["key"]
            first = tts.voice_for(kokoro.tokenizer.phonemize(text))
            best = None
            for voice in [first] + [v for v, _ in tts.RETRY if v != first]:
                audio, sr = say(kokoro, text, voice)
                heard = tts.hear(base, tts.resample16k(audio, sr), beam=5)
                score = tts.similar(heard, text)
                if best is None or score > best[3]:
                    best = (audio, sr, voice, score, heard)
                if score >= PASS:
                    break
            audio, sr, voice, score, heard = best
            if score < PASS:
                stuck.append(f"{text!r} heard {heard!r} ({score:.2f})")
            slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:48]
            dst = tts.write_hashed(audio, sr, f"course/{slug}")
            old = m.get(text, {}).get("file")
            if old and old != f"tts/course/{dst.name}":
                (tts.DATA / old).unlink(missing_ok=True)
            m[text] = {"file": f"tts/course/{dst.name}", "voice": voice, "heard": heard, "match": round(score, 2),
                       "seconds": round(len(audio) / sr, 2)}
            if n % 20 == 0 or n == len(todo):
                MANIFEST.write_text(json.dumps(m, ensure_ascii=False, indent=0, sort_keys=True), encoding="utf-8")
                print(f"  {n}/{len(todo)} · {n / (time.time() - t0):.1f}/s", flush=True)
        if stuck:
            print(f"{len(stuck)} heard differently by every voice (listen to them):", *stuck, sep="\n  ")
    keys = [r["key"] for r in rows]
    # Recordings of sentences the lessons no longer have.
    for k in [k for k in m if k not in set(keys)]:
        (tts.DATA / m.pop(k)["file"]).unlink(missing_ok=True)
    MANIFEST.write_text(json.dumps(m, ensure_ascii=False, indent=0, sort_keys=True), encoding="utf-8")
    write_map(m, keys)
    size = sum((tts.DATA / m[k]["file"]).stat().st_size for k in keys if k in m)
    print(f"{MAP.relative_to(ROOT)}: {len(keys)} recordings, {size / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
